export function generate(root, cfg) {
  const sources = cfg.sources || [];
  const abs = s => resolve(root, s.path);
  const tokens = {};
  const skipped = [];
  const perSource = [];
  for (const s of sources) {
    let got = {};
    if (s.type === 'css') got = importCss([abs(s)], root);
    else if (s.type === 'dtcg') { const r = importDtcg([abs(s)], root); got = r.tokens; skipped.push(...r.skipped); }
    else if (s.type === 'figma') { const r = importFigma([abs(s)], root); got = r.tokens; skipped.push(...r.skipped); }
    perSource.push({ source: s, tokens: got });
    for (const [k, v] of Object.entries(got)) if (!tokens[k]) tokens[k] = v; // earlier sources win
  }

  // Aliases resolve against the merged set, so var(--color-brand) means the brand that won.
  for (const t of Object.values(tokens)) { delete t.resolved; delete t.channels; delete t.hex; }
  finishTokens(tokens);

  // Drift: a token two sources both define, with different values (Figma against code, usually).
  const rootPx = Number(cfg.rootPx) || 16;
  const drift = [];
  for (const name of Object.keys(tokens)) {
    const holders = perSource.filter(p => p.tokens[name]);
    if (holders.length < 2) continue;
    const values = holders.map(p => ({ path: p.source.path, type: p.source.type, value: p.tokens[name].resolved ?? p.tokens[name].value, comparable: comparable(p.tokens[name], rootPx), figma: p.tokens[name].figma }));
    if (new Set(values.map(v => v.comparable)).size > 1) drift.push({ token: name, values });
  }
  const figmaNames = new Set(perSource.filter(p => p.source.type === 'figma').flatMap(p => Object.keys(p.tokens)));
  const codeNames = new Set(perSource.filter(p => p.source.type !== 'figma' && !COMPONENT_TYPES.includes(p.source.type)).flatMap(p => Object.keys(p.tokens)));
  const onlyInFigma = figmaNames.size && codeNames.size ? [...figmaNames].filter(n => !codeNames.has(n)).length : 0;
  const nativeApps = writeNative(root, sources, cfg.nativeExtras);
  const react = sources.filter(s => COMPONENT_TYPES.includes(s.type));
  const { components } = react.length ? importReact(react.map(abs), root) : { components: {} };

  const dir = join(root, OUT);
  mkdirSync(dir, { recursive: true });
  const catalog = {
    meta: {
      tailwind: cfg.tailwind !== undefined ? cfg.tailwind : detectTailwind(root, sources),
      drift,
      onlyInFigma,
      _comment: 'GENERATED by ds-enforcer from the sources in enforcer.config.json. Do not edit; change the sources and run `npx ds-enforcer sync` (the MCP server also resyncs when a source changes).',
      framework: cfg.framework,
      sources,
      generatedAt: new Date().toISOString(),
    },
    components,
    tokens,
    legacy: { classes: [] },
    recipes: {},
  };
  writeFileSync(join(dir, 'catalog.json'), JSON.stringify(catalog, null, 2) + '\n');
  const css = `/* GENERATED by ds-enforcer: every token, as the enforcer reads it. Do not edit. */\n:root {\n${Object.entries(tokens).map(([k, t]) => `  ${k}: ${t.channels ? `${t.hex}; /* hsl(var(${k})): ${t.value} */` : t.hex ? `${t.hex}; /* ${t.value} */` : `${t.value};`}`).join('\n')}\n}\n`;
  writeFileSync(join(dir, 'tokens.css'), css);
  const syn = join(dir, 'synonyms.json');
  const synonyms = existsSync(syn) ? JSON.parse(readFileSync(syn, 'utf8')) : {
    _comment: 'Yours to edit: the words people use for a component or token that its name and summary do not contain, e.g. "Dialog": ["modal", "popup"], "--color-danger": ["red text", "error"]. Sync adds starter words only for common components with no entry here; it never changes an entry you have.',
    components: {}, tokens: {}, recipes: {},
  };
  synonyms.components ||= {};
  let seeded = 0;
  for (const name of Object.keys(components)) {
    const seed = SEEDS[name.toLowerCase()];
    if (seed && !(name in synonyms.components)) { synonyms.components[name] = seed; seeded++; }
  }
  if (seeded || !existsSync(syn)) writeFileSync(syn, JSON.stringify(synonyms, null, 2) + '\n');

  const groups = {};
  for (const t of Object.values(tokens)) groups[t.group] = (groups[t.group] || 0) + 1;
  return { tokens: Object.keys(tokens).length, groups, components: Object.keys(components).length, skipped, tailwind: catalog.meta.tailwind, drift, onlyInFigma, nativeApps };
}

/**
 * Write the config and generate. An existing config at the root is kept and
 * updated; one this project wrote by hand (no `sources`) is replaced only with
 * replace: true, so init can never silently take over a hand-tuned setup.
 */
export function connect(root, { sources, rootPx = 16, rules = {}, replace = false }) {
  const path = join(root, 'enforcer.config.json');
  const existing = existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
  if (existing && !existing.sources && !replace) {
    throw new Error(`${path} was written by hand (it has no "sources"). Pass replace to overwrite it.`);
  }
  if (!sources?.length) throw new Error('Choose at least one source to connect.');
  // The components' framework decides which checks run on markup: react, vue or svelte.
  const framework = ['react', 'vue', 'svelte'].find(t => sources.some(s => s.type === t)) || 'css';
  const hasSwift = sources.some(s => s.type === 'swift');
  const houseRule = (on, base) => ({ ...base, enabled: Boolean(on) });
  const cfg = {
    ...(existing || {}),
    // The config format this code reads (config-file.js); a file without it reads as older.
    configVersion: CONFIG_VERSION,
    projectRoot: '.',
    framework,
    sources: sources.map(({ type, path: p }) => ({ type, path: p })),
    ...(hasSwift ? { nativeManifest: NATIVE } : {}),
    tokensCss: `${OUT}/tokens.css`,
    catalog: `${OUT}/catalog.json`,
    synonyms: `${OUT}/synonyms.json`,
    rootPx: Number(rootPx) || 16,
    exemptFiles: [...new Set([...(existing?.exemptFiles || []), ...sources.filter(s => s.type === 'css').map(s => basename(s.path))])],
    rules: {
      pureBlack: houseRule(rules.pureBlack, { severity: 'high', message: 'Pure black (#000) is not allowed in this design system', suggestion: 'Use the darkest ink token' }),
      pureWhite: houseRule(rules.pureWhite, { severity: 'medium', message: 'Pure white backgrounds are not allowed in this design system', suggestion: 'Use a surface or page background token' }),
    },
  };
  writeFileSync(path, JSON.stringify(cfg, null, 2) + '\n');
  return { configPath: path, framework, ...generate(root, cfg) };
}

/**
 * Add the PostToolUse hook (check each edit) and the Stop hook (show the report when
 * Claude finishes, if anything is left) to the project's .claude/settings.local.json (personal, not
 * committed: the command holds this machine's path to the enforcer). Keeps every other
 * setting; does nothing if a ds-enforcer hook is already there.
 */
export function installHook(root) {
  const dir = join(root, '.claude');
  const path = join(dir, 'settings.local.json');
  let settings = {};
  if (existsSync(path)) {
    try { settings = JSON.parse(readFileSync(path, 'utf8')); } catch { return { path, installed: false, reason: 'its JSON did not parse, so it was left alone' }; }
  }
  const bin = resolve(import.meta.dirname, '..', 'bin', 'ds-enforcer.mjs');
  const command = `node "${bin}" hook`;
  settings.hooks ||= {};
  settings.hooks.PostToolUse ||= [];
  settings.hooks.Stop ||= [];
  const has = (list, re) => list.some(e => (e.hooks || []).some(h => re.test(h.command || '')));
  const hasEdit = has(settings.hooks.PostToolUse, /ds-enforcer(\.mjs)?"? hook\b/);
  const hasStop = has(settings.hooks.Stop, /ds-enforcer(\.mjs)?"? stop-hook\b/);
  if (hasEdit && hasStop) return { path, installed: false, reason: 'already installed' };
  if (!hasEdit) settings.hooks.PostToolUse.push({ matcher: 'Edit|Write|NotebookEdit', hooks: [{ type: 'command', command, timeout: 30 }] });
  if (!hasStop) settings.hooks.Stop.push({ hooks: [{ type: 'command', command: `node "${bin}" stop-hook`, timeout: 60 }] });
  mkdirSync(dir, { recursive: true });
  writeFileSync(path, JSON.stringify(settings, null, 2) + '\n');
  return { path, installed: true };
}

/** A fingerprint of every source file, so a change to one triggers a resync. */
export function sourceStamp(root, sources = []) {
  const parts = [];
  for (const s of sources) {
    const abs = resolve(root, s.path);
    if (COMPONENT_TYPES.includes(s.type)) {
      const files = walk(abs, { accept: p => /\.(tsx|jsx|vue|svelte)$/.test(p) });
      parts.push(files.length, Math.max(0, ...files.map(f => { try { return statSync(f).mtimeMs; } catch { return 0; } })));
    } else {
      try { parts.push(statSync(abs).mtimeMs); } catch { parts.push(0); }
    }
  }
  return parts.join(':');
}
