/**
 * Connect a project: write enforcer.config.json at its root and generate
 * .ds-enforcer/ (catalog.json, tokens.css, synonyms.json) from the sources it
 * names. `generate` reruns the import alone, which is all a sync needs.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync, readdirSync } from 'fs';
import { join, resolve, basename } from 'path';
import { importCss, importDtcg, importReact, importFigma, walk, finishTokens, swiftAppFor, COMPONENT_TYPES } from './importers.mjs';

const NATIVE = '.ds-enforcer/native.json';
const readdirSafe = d => { try { return readdirSync(d); } catch { return []; } };

/**
 * The native manifest for the SwiftUI theme files init connected: one app per
 * Xcode project or Swift package, its theme files, and no house fonts or sanctioned
 * scopes until the team adds them. Rewritten on every sync; edit enforcer.config.json's
 * sources, not this file.
 */
function writeNative(root, sources, extras = {}) {
  const swift = sources.filter(s => s.type === 'swift');
  if (!swift.length) return null;
  const apps = {};
  for (const s of swift) {
    const app = swiftAppFor(root, resolve(root, s.path)) || { key: 'app', name: 'App', root: '.', source: s.path.split('/').slice(0, -1).join('/') || '.', platform: 'ios' };
    const xcodeproj = readdirSafe(resolve(root, app.root)).find(n => n.endsWith('.xcodeproj'));
    const entry = apps[app.key] ||= { name: app.name, platform: app.platform, ui: 'SwiftUI', root: app.root, source: app.source,
      ...(xcodeproj ? { project: `${app.root === '.' ? '' : app.root + '/'}${xcodeproj}`, scheme: app.name } : {}),
      themeFiles: [], annotation: 'None: constants are matched to web tokens by value. A trailing // --token comment on a constant names the token it mirrors.', sanctionedScopes: { ...(extras.apps?.[app.key]?.sanctionedScopes || {}) } };
    if (!entry.themeFiles.includes(s.path)) entry.themeFiles.push(s.path);
  }
  const manifest = { native: { _comment: 'GENERATED by ds-enforcer from the SwiftUI theme files in enforcer.config.json sources. Add brandFonts, iconFonts or sanctionedScopes in enforcer.config.json under nativeExtras; this file is rewritten on sync.', baseline: '.ds-enforcer/native-baseline.json', brandFonts: extras.brandFonts || [], iconFonts: extras.iconFonts || [], apps } };
  mkdirSync(join(root, '.ds-enforcer'), { recursive: true });
  writeFileSync(join(root, NATIVE), JSON.stringify(manifest, null, 2) + '\n');
  return Object.keys(apps).length;
}
import { parseColor, toHex } from '../colour.js';
import { CONFIG_VERSION } from '../config-file.js';

/* One comparable form per value: colours as hex (+alpha), lengths in px, the rest as written. */
function comparable(t, rootPx) {
  if (t.hex) return t.hex;
  const v = String(t.resolved ?? t.value).trim();
  const c = parseColor(v);
  if (c) return toHex(c) + (c.a < 1 ? `/${Math.round(c.a * 100)}` : '');
  const len = v.match(/^(-?[\d.]+)(px|rem)$/);
  if (len) return `${len[2] === 'rem' ? +len[1] * rootPx : +len[1]}px`;
  return v.toLowerCase().replace(/\s+/g, ' ');
}

/** "v4", "v3" or false: from the tailwindcss dependency, else the CSS and config files. */
export function detectTailwind(root, sources = []) {
  try {
    const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    const v = { ...pkg.dependencies, ...pkg.devDependencies }.tailwindcss;
    if (v) return /^[^\d]*4/.test(v) ? 'v4' : 'v3';
  } catch { /* no package.json */ }
  for (const s of sources.filter(s => s.type === 'css')) {
    try {
      const css = readFileSync(resolve(root, s.path), 'utf8');
      if (/@import\s+["']tailwindcss["']|@theme\b/.test(css)) return 'v4';
      if (/@tailwind\s+(base|components|utilities)/.test(css)) return 'v3';
    } catch { /* unreadable source */ }
  }
  for (const f of ['tailwind.config.js', 'tailwind.config.cjs', 'tailwind.config.mjs', 'tailwind.config.ts']) if (existsSync(join(root, f))) return 'v3';
  return false;
}

